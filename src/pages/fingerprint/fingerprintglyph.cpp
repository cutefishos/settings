Path fingerprintGlyph(double size)
{
    Path lines;
    const double* at = kDashes;
    const double* end = kDashes + sizeof(kDashes) / sizeof(kDashes[0]);
    while (at < end) {
        const int count = int(*at++);
        lines.moveTo(at[0] * size, at[1] * size);
        for (int i = 1; i < count; ++i)
            lines.lineTo(at[2 * i] * size, at[2 * i + 1] * size);
        at += 2 * count;
    }
    return lines.stroked(kStrokeWidth * size, LineCap::Round, LineJoin::Round);
}

