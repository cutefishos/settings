cutefish::ui::Path fingerprintGlyph(double size)
{
    cutefish::ui::Path path;
    const double* at = kOutline;
    const double* end = kOutline + sizeof(kOutline) / sizeof(kOutline[0]);
    while (at < end) {
        switch (int(*at++)) {
        case 0:
            path.moveTo(at[0] * size, at[1] * size);
            at += 2;
            break;
        case 1:
            path.quadTo(at[0] * size, at[1] * size, at[2] * size, at[3] * size);
            at += 4;
            break;
        default:
            path.close();
            break;
        }
    }
    return path;
}

